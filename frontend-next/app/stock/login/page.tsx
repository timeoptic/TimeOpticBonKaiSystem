"use client";

/**
 * ทางผ่านไปหน้าล็อกอินใบเดียวของทั้งแอป
 *
 * ฝั่งคลังเคยมีหน้าล็อกอินของตัวเอง คนละดีไซน์กับหน้าร้าน ทั้งที่ใช้ session
 * ใบเดียวกัน · ตอนนี้เหลือใบเดียวที่ `/login/` แต่ลิงก์เก่ายังอยู่ในบุ๊กมาร์ก
 * และในหัวคน หน้านี้จึงยังอยู่เพื่อพาไปที่ใหม่ ไม่ใช่เพื่อขึ้นว่าไม่พบหน้า
 *
 * ใช้ `location.replace` ไม่ใช่ router: หน้าปลายทางอยู่คนละกลุ่ม CSS และ
 * `replace` ทำให้ปุ่มย้อนกลับไม่เด้งกลับมาที่นี่แล้ววนอีกรอบ
 */
import { useEffect } from "react";

export default function StockLoginRedirect() {
  useEffect(() => {
    location.replace("/login/");
  }, []);

  return <p className="field__help">กำลังพาไปหน้าเข้าสู่ระบบ…</p>;
}
