"use client";

import { useEffect } from "react";

/**
 * หน้าข้างหลังห้ามเลื่อน ตอนที่มีกล่องหรือแผ่นเปิดอยู่
 *
 * `<dialog showModal()>` กันการ *กด* ของข้างหลังให้แล้ว แต่ไม่ได้กันการ *ไถ* —
 * บนมือถือการไถบนกล่องที่เลื่อนจนสุดแล้วจะไปเลื่อนหน้าข้างหลังต่อ พอปิดกล่อง
 * หน้าจึงไปโผล่คนละที่กับตอนเปิด และของที่กำลังอ่านอยู่ก่อนกดก็หายไป
 *
 * เก็บค่าเดิมไว้แล้วคืนตอนปิด ไม่ได้เซ็ตเป็นค่าว่างทับ — กล่องซ้อนกันได้ (ลิ้นชัก
 * สินค้าเปิดกล่องยืนยันอีกที) และการคืนค่าแบบเก็บของเดิมไว้ทำให้ชั้นในสุดปิดแล้ว
 * ชั้นนอกยังล็อกอยู่ตามที่ควรเป็น
 *
 * ที่เดียวสำหรับทุกกล่อง — เขียนซ้ำในแต่ละคอมโพเนนต์คือสี่ที่ที่ต้องจำให้ตรงกัน
 */
export default function useScrollLock(active: boolean): void {
  useEffect(() => {
    if (!active) return;
    const had = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      document.body.style.overflow = had;
    };
  }, [active]);
}
