/**
 * ราคาขายเลนส์ "คู่" กับราคารายข้าง R/L — สองมุมมองของเลขชุดเดียวกัน
 *
 * ฐานข้อมูลเก็บแค่ lens_od_price (ขวา) กับ lens_os_price (ซ้าย) เหมือนเดิม ไม่มี
 * คอลัมน์ราคาคู่ เพราะถ้าเก็บทั้งสองอย่างจะมีวันที่มันไม่ตรงกัน แล้วไม่มีใครรู้ว่า
 * ใบไหนจริง · ราคาคู่ที่หน้าจอโชว์จึงคือผลบวกของสองข้างเสมอ ส่วนการกรอกราคาคู่คือ
 * คำสั่ง "แบ่งลงสองข้าง" ครั้งเดียว หลังจากนั้นแก้รายข้างทับได้ตามปกติ
 */

const n = (v) => {
  const x = Number(v);
  return Number.isFinite(x) ? x : 0;
};

/** ปัดให้ลงคอลัมน์ decimal(10,2) ได้พอดี ไม่ทิ้งเศษทศนิยมลอย ๆ จากการหาร */
const round2 = (v) => Math.round((v + Number.EPSILON) * 100) / 100;

/**
 * แบ่งราคาคู่ลงสองข้างข้างละครึ่ง — ข้างซ้ายรับส่วนต่างที่เหลือจากการปัด ผลรวม
 * ของสองข้างจึงเท่ากับราคาคู่ที่พิมพ์เป๊ะ ๆ เสมอ (4,001 → 2,000.50 + 2,000.50)
 * ค่าว่าง ค่าที่ไม่ใช่ตัวเลข และค่าติดลบ อ่านเป็น 0 ทั้งหมด
 */
export function splitPairPrice(pair) {
  const total = Math.max(0, round2(n(pair)));
  const od = round2(total / 2);
  return { od, os: round2(total - od) };
}

/** ราคาคู่ที่เอาไปโชว์ = ผลบวกของราคาสองข้างที่บันทึกไว้จริง */
export const pairPrice = (od, os) => round2(n(od) + n(os));

/**
 * ข้อความในช่องราคาคู่ตอนที่ไม่ได้พิมพ์อยู่ — ราคา 0 หรือค่าที่ใช้ไม่ได้ เป็นช่องว่าง
 *
 * 0 คือ "ยังไม่ตั้งราคา" · ถ้าโชว์ "0" จริง ๆ ในช่อง คนที่จะกรอกราคาต้องลบเลข 0 ก่อน
 * ทุกครั้ง ช่องว่างกับ placeholder "0" บอกความหมายเดียวกันโดยไม่ขวางการพิมพ์
 */
export function pairDisplay(pair) {
  const x = Number(pair);
  return Number.isFinite(x) && x > 0 ? String(x) : '';
}
