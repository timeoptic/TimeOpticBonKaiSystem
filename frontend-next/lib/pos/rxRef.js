/**
 * ค่าสายตาอ้างอิงของ POS — ฟังก์ชันบริสุทธิ์ล้วน ไม่มี React ไม่มี fetch
 *
 * ใช้ตอนขายคอนแทคเลนส์: ระบบ **ไม่เติมค่าให้อัตโนมัติ** พนักงานกรอกค่าของกล่องเอง
 * ที่นี่มีหน้าที่เดียวคือหยิบใบที่ควรเอามาโชว์ข้าง ๆ ช่องกรอก ให้พนักงานเทียบด้วยตา
 *
 * เหตุผลที่ต้องข้ามรอบที่ยังไม่มีใบ final: รอบที่วัดค้างไว้ยังไม่ใช่ค่าที่ยืนยันว่าจะใช้
 * หยิบมาโชว์แล้วพนักงานเข้าใจว่านั่นคือค่าล่าสุดของลูกค้า ซึ่งยังไม่จริง
 */
import { sphPower, cylPower } from '../format.js';

/**
 * รอบวัดล่าสุดของลูกค้าที่ "มีใบ final แล้ว"
 *
 * รับผลจาก GET /api/customers/:id/exam-sessions ซึ่งเรียงรอบใหม่ไปเก่ามาแล้ว
 * คืนทั้งรอบ ไม่ใช่แค่ใบ final เพราะหน้า POS ต้องโชว์วันที่วัดและเลขเคสที่มาด้วย
 */
export function latestFinalSession(sessions) {
  if (!Array.isArray(sessions)) return null;
  return sessions.find((s) => s && s.final) || null;
}

/* ข้างที่ขายได้: ขวา ซ้าย หรือกล่องที่ใช้ค่าเดียวกันทั้งสองตา */
const EYE_KEYS = { R: ['r'], L: ['l'], RL: ['r', 'l'] };
const EYE_LABEL = { r: 'R', l: 'L' };

/* รูปแบบเดียวกับแถวสรุปรอบตรวจใน ExamHistory — ค่าเดียวกันต้องหน้าตาเดียวกันทุกที่
   AXIS เป็นจำนวนเต็ม ไม่ใช่กำลังเลนส์ จึงไม่ผ่านตัวจัดรูปแบบกำลังสายตา */
const oneEye = (row, k) => `${EYE_LABEL[k]} ${sphPower(row[`${k}_sphere`])}`
  + ` / ${cylPower(row[`${k}_cylinder`])} × ${row[`${k}_axis`] || '—'}`;

/**
 * ข้อความค่าอ้างอิงของข้างที่พนักงานเลือกไว้ในแถวตะกร้า
 *
 * ยังไม่แนบใบวัด หรือข้างที่ไม่รู้จัก คืนข้อความว่าง — ให้หน้าจอไม่ต้องแสดงอะไรเลย
 * ดีกว่าโชว์ขีดเปล่า ๆ ที่อ่านแล้วนึกว่าใบวัดไม่มีค่า
 */
export function eyeRefText(row, eye) {
  if (!row) return '';
  const keys = EYE_KEYS[eye];
  if (!keys) return '';
  return keys.map((k) => oneEye(row, k)).join(' · ');
}
