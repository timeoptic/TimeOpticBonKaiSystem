/** ตัวเลือก "กี่รายการต่อหน้า" — เรียงจากน้อยไปมาก ตัวแรกคือค่าเริ่มต้นของทั้งแอป
 *
 * ห้าแถวเป็นค่าเริ่มต้น ตามที่ร้านขอ — ตารางส่วนใหญ่ในแอปเป็นผลของตัวกรองที่แคบ
 * อยู่แล้ว และหน้าจอที่ใช้งานจริงคือมือถือ ซึ่งสิบแถวคือเลื่อนพ้นจอไปหนึ่งจอครึ่ง
 * ก่อนจะเจอแถบแบ่งหน้า · ใครอยากเห็นมากกว่านั้นเลือกจากช่องข้าง ๆ แถบได้เหมือนเดิม
 */
export const PAGE_SIZES = [5, 10, 25, 50];

/**
 * ชุดของกระดานงาน — ใหญ่กว่าของทั้งแอปหนึ่งขั้น
 *
 * ตารางอื่นในแอปคือผลของตัวกรองที่แคบอยู่แล้ว (คิววันนี้ ขั้นตอนเดียว) สิบแถว
 * แรกมักคือทั้งหมดที่มี · กระดานงานคือกองงานทั้งร้าน หลักร้อยถึงหลักพัน คนเปิด
 * มากวาดตาหาใบที่ต้องการ ไม่ได้มาอ่านทีละใบ — หน้าละสิบแปลว่าต้องกดเลขหน้า
 * 118 ครั้งกว่าจะครบ 1,173 เคส
 *
 * แยกชุดแทนที่จะขยาย PAGE_SIZES ทั้งแอป เพราะหน้าอื่นตั้งใจให้สั้น
 */
export const BOARD_PAGE_SIZES = [20, 50, 100];

/**
 * แถวน้อยพอที่ทุกตัวเลือกจะให้ผลเหมือนกันหมดหรือยัง
 *
 * ใช้ตัดสินว่าจะซ่อนแถบแบ่งหน้าทิ้งได้ไหม · เกณฑ์คือ "น้อยกว่าตัวเลือกที่เล็กที่สุด"
 * ไม่ใช่ "น้อยกว่าค่าที่เลือกอยู่" — ครั้งแรกเขียนเป็น total <= perPage แล้วเจอว่า
 * ข้อมูล 19 แถวพอเลือก 50 แถบหายไปทั้งแถบ *พร้อมช่องเลือก* กลับมาเป็น 10 ไม่ได้
 * จนกว่าจะรีโหลดหน้า · ตัวควบคุมที่ซ่อนตัวเองตามค่าที่มันเพิ่งถูกตั้งคือทางตัน
 */
export const fitsOnePage = (total, sizes = PAGE_SIZES) => total <= Math.min(...sizes);

/**
 * เลขหน้าที่จะโชว์: 1 … 5 6 7 … 12 — ไม่เกินเจ็ดช่องไม่ว่าจะกี่หน้า
 *
 * เพดานเจ็ดช่องไม่ใช่เรื่องความสวย: แถบที่กว้างขึ้นตามจำนวนหน้าจะดันตัวเลือก
 * "กี่รายการต่อหน้า" ตกบรรทัดบนจอร้าน
 */
export function pageWindow(page, pages) {
  if (pages <= 7) return Array.from({ length: pages }, (_, i) => i + 1);
  const out = [1];
  const from = Math.max(2, page - 1);
  const to = Math.min(pages - 1, page + 1);
  if (from > 2) out.push('…');
  for (let n = from; n <= to; n++) out.push(n);
  if (to < pages - 1) out.push('…');
  out.push(pages);
  return out;
}

/**
 * แถวของหน้าที่กำลังดู
 *
 * `page` ที่เกินจำนวนหน้าจริงถอยมาหน้าสุดท้ายแทนที่จะคืนอาเรย์ว่าง — เกิดตอน
 * กรองจนแถวลดลงแต่ state ยังชี้หน้าเดิม · ตารางโล่งทั้งที่ badge บอกว่ามีข้อมูล
 * อ่านเหมือนแอปพัง ไม่ใช่เหมือนตัวกรอง
 */
export function sliceOf(rows, page, perPage) {
  const all = rows || [];
  const pages = Math.max(1, Math.ceil(all.length / perPage));
  const current = Math.min(Math.max(1, page), pages);
  return all.slice((current - 1) * perPage, current * perPage);
}
