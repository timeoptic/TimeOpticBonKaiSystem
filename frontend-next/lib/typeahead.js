/**
 * พิมพ์ตัวอักษรเพื่อกระโดดไปตัวเลือกในรายการ — สิ่งที่ `<select>` ของเบราว์เซอร์
 * ทำให้ฟรี และหายไปทันทีที่วาดรายการเอง
 *
 * คนคีย์ข้อมูลที่ร้านใช้ท่านี้จริงกับรายการพนักงานและรายการสถานะที่ยาว การกาง
 * รายการแล้วเลื่อนหาด้วยเมาส์ช้ากว่าพิมพ์ตัวแรกของชื่อมาก
 *
 * แยกออกมาจาก component เพราะเป็นตรรกะล้วน ๆ ที่เทสได้โดยไม่ต้องมี DOM
 */

/**
 * ดัชนีของตัวเลือกที่ควรกระโดดไป · ไม่มีตัวไหนตรงคืน -1 (ไม่ใช่ 0 ซึ่งจะเป็นการ
 * เลือกตัวแรกให้เองทั้งที่คนพิมพ์ผิด)
 *
 * `buffer` คือตัวอักษรที่พิมพ์ติด ๆ กันในช่วงเวลาสั้น ๆ ตัวเรียกเป็นคนเก็บและล้างเอง
 *
 * สองพฤติกรรมที่ต่างกันและต้องแยกให้ออก ตามที่ `<select>` ทำมาแต่เดิม:
 *   กดตัวเดิมซ้ำ ('สสส') = "ตัวถัดไปที่ขึ้นต้นด้วย ส" — ชื่อไทยขึ้นต้นเหมือนกันหลายคน
 *   พิมพ์ต่อเป็นคำ ('สมห') = กรองให้แคบลง เริ่มนับจากตัวที่ชี้อยู่ ไม่เดินหนีจากตัวที่ยังตรง
 */
export function typeaheadIndex(labels, buffer, current) {
  const q = String(buffer ?? '').trim().toLowerCase();
  const n = (labels || []).length;
  if (!q || !n) return -1;

  const repeat = [...q].every((ch) => ch === q[0]);
  const needle = repeat ? q[0] : q;
  /* ตัวเดียวหรือกดซ้ำ = เดินต่อจากตัวที่ชี้อยู่ · พิมพ์เป็นคำ = เริ่มนับที่ตัวที่ชี้อยู่เลย */
  const from = repeat ? (current < 0 ? 0 : current + 1) : Math.max(current, 0);

  for (let i = 0; i < n; i++) {
    const idx = (from + i) % n;
    if (String(labels[idx] ?? '').trim().toLowerCase().startsWith(needle)) return idx;
  }
  return -1;
}
