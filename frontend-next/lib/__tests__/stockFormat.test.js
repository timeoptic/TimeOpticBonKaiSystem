import test from 'node:test';
import assert from 'node:assert/strict';
import { date, dateTime } from '../../stockmod/lib/format.ts';

/* หน้าความเคลื่อนไหวของคลังเคยบอกแค่วันที่ — สองรายการของสินค้าตัวเดียวกันในวันเดียวกัน
   จึงบอกไม่ได้ว่าอันไหนเกิดก่อน · เวลาที่ฐานเก็บเป็นเวลาไทยอยู่แล้ว (session +07:00)
   จึงต้องขึ้นตามนั้นตรง ๆ ไม่เลื่อนอีกเจ็ดชั่วโมง */
test('วันที่พร้อมเวลา ชั่วโมง:นาที ตามที่ฐานเก็บ', () => {
  assert.equal(dateTime('2026-09-12 09:57:03'), `${date('2026-09-12')} 09:57`);
  assert.equal(dateTime('2026-09-12 00:05:00'), `${date('2026-09-12')} 00:05`);
  assert.equal(dateTime('2026-09-12 23:59:59'), `${date('2026-09-12')} 23:59`);
});

test('ค่าที่ไม่มีเวลา ขึ้นแค่วันที่ · ไม่มีค่า ขึ้นขีด', () => {
  assert.equal(dateTime('2026-09-12'), date('2026-09-12'));
  assert.equal(dateTime(null), '—');
});
