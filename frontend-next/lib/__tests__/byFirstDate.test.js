import test from 'node:test';
import assert from 'node:assert/strict';
import { byFirstDate } from '../../stockmod/lib/byFirstDate.ts';

/* ร้านแจ้ง 22 ต.ค. 2026: ชีตแยกตามออเดอร์เรียงเลขออเดอร์เป็นข้อความ วันที่จึงกระโดด */
test('ก้อนเรียงตามวันแรกของก้อน ไม่ใช่ตามชื่อ · ในก้อนเรียงตามเวลา', () => {
  const rows = [
    { doc: '10451', at: '2026-09-23 17:52:00' },
    { doc: '2026-00056', at: '2026-10-01 11:24:00' },
    { doc: '2722', at: '2026-10-02 15:52:00' },
    { doc: '59181', at: '2026-09-29 10:42:00' },
    { doc: '2722', at: '2026-09-20 08:00:00' },
    { doc: 'RX-2026-0082', at: '2026-09-30 17:54:00' },
  ];
  const out = byFirstDate(rows, (r) => r.doc, (r) => r.at).map((r) => `${r.doc} ${r.at.slice(5, 10)}`);
  assert.deepEqual(out, [
    '2722 09-20',
    '2722 10-02',
    '10451 09-23',
    '59181 09-29',
    'RX-2026-0082 09-30',
    '2026-00056 10-01',
  ]);
});
