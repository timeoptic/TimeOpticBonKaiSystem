/** ทุก href ที่คู่มือพาไป — ใช้ในเทสต์ตรวจว่าไม่มีลิงก์ตาย */
export function manualLinks(manual) {
  return manual.flatMap((s) => (s.open || []).map((o) => o.href));
}

/** ข้อความทุกชิ้นที่คนอ่านเห็น — ไม่รวม id / href / icon / ชนิดบล็อก */
export function manualStrings(manual) {
  const SKIP = new Set(['id', 'href', 'icon', 'type', 'tone', 'group']);
  const out = [];
  const walk = (v, key) => {
    if (SKIP.has(key)) return;
    if (typeof v === 'string') out.push(v);
    else if (Array.isArray(v)) v.forEach((x) => walk(x));
    else if (v && typeof v === 'object') Object.entries(v).forEach(([k, x]) => walk(x, k));
  };
  walk(manual);
  return out;
}
