-- Idempotency store for every request that changes stock.
--
-- Why a table and not a unique index on inventory_logs: one deduction can cut
-- across several lots and therefore write several log rows, so there is no
-- single row to hang a unique constraint on. The request is the thing that
-- happens once, so the request is what we key.
--
-- The flow is: insert the key first (inside the same transaction as the cut).
-- A duplicate key collides on uq_stock_req, which tells us the work was already
-- done — we then read `response` and hand back the identical answer instead of
-- cutting a second time.

CREATE TABLE IF NOT EXISTS stock_requests (
  id           INT UNSIGNED NOT NULL AUTO_INCREMENT,

  -- Who asked. 'pos' for the shop-floor system, 'web' for our own screens.
  source       VARCHAR(30)  NOT NULL,

  -- Stable across retries and generated by the caller before it sends.
  -- e.g. "job:1042:left" from a lens job, or "adhoc:<uuid>" from a form.
  idem_key     VARCHAR(120) NOT NULL,

  action       ENUM('ISSUE','SCRAP','RETURN') NOT NULL,
  sku          VARCHAR(100) NOT NULL,
  quantity     INT NOT NULL,

  -- admins.id. No foreign key: this table must keep working while the people
  -- table is being migrated, and a request record outliving a deleted person
  -- is better than a stock write failing.
  actor_id     INT UNSIGNED NULL,

  -- 'failed' rows are kept on purpose: a refused request is evidence, and
  -- repeated shortages on one SKU are worth seeing.
  status       ENUM('done','failed') NOT NULL,

  -- The exact JSON that was returned, replayed verbatim on a duplicate.
  response     LONGTEXT NULL,

  created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

  PRIMARY KEY (id),
  UNIQUE KEY uq_stock_req (source, idem_key),
  KEY idx_stock_req_sku (sku, created_at),
  KEY idx_stock_req_actor (actor_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
