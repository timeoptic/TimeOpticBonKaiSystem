-- เลขรับของที่มากับเลนส์ RX — ร้านขอไว้ 18 ก.ย. 2026
--
-- เลนส์สั่งตัดมาจากผู้ขายพร้อมเลขรับ (เลขใบส่งของ / เลขงานของแล็บ) ทุกครั้ง · คนรับของที่คลัง
-- ติ๊กว่าเลนส์มาแล้วบนหน้าใบสั่งตัด ป๊อปอัพถามเลขนี้ตอนติ๊ก แล้วเก็บไว้คู่กับเวลามาถึง
-- เพื่อเทียบกับใบวางบิลของผู้ขายทีหลัง และตอบได้ว่าเลนส์ข้างนี้มากับกล่องไหน
--
--   arrived_ref  NULL = ยังไม่มา หรือมาก่อนมีช่องนี้ · เอาติ๊กออกแล้วล้างเป็น NULL ด้วย

ALTER TABLE rx_orders
  ADD COLUMN arrived_ref VARCHAR(100) NULL DEFAULT NULL
    COMMENT 'เลขรับของที่มากับเลนส์ตอนติ๊กว่ามาถึง'
    AFTER arrived_by;
