-- คนที่ทำของเสีย เป็นชื่อที่พิมพ์ ไม่ใช่บัญชีผู้ใช้
--
-- ร้านขอไว้ 12 ก.ย. 2026: ผู้ดูแลคลังเป็นคนคีย์การตัดของเสีย แต่คนทำเสียจริงมักเป็น
-- เด็กฝึกงานที่มาไม่นานแล้วก็ไป · สร้างบัญชีให้ทุกคนแปลว่ารายชื่อผู้ใช้จะรกไปด้วยคนที่
-- ไม่อยู่แล้ว ส่วนช่องเดิม (`issued_to_admin_id`) เลือกได้แต่คนที่มีบัญชี และหน้าจอตั้ง
-- เป็นคนที่ล็อกอินอยู่ให้เอง ของเสียของน้องฝึกงานจึงไปขึ้นชื่อผู้ดูแลคลังในแดชบอร์ด
--
-- ช่องนี้ใช้กับแถว SCRAP เท่านั้นและต้องกรอกทุกครั้ง (ตรวจที่ `Stock::recipient`) · คนคีย์
-- ยังอยู่ที่ `created_by` เหมือนเดิม ไม่มีใครต้องเลือก · แถวของเสียเก่าที่ระบุคนทำไว้ด้วย
-- บัญชียังนับตามชื่อบัญชีนั้น (ดู `Reports::overview`)

ALTER TABLE inventory_logs
  ADD COLUMN scrap_by VARCHAR(120) NULL DEFAULT NULL
    COMMENT 'ชื่อคนที่ทำของเสีย (พิมพ์เอง) · เฉพาะ SCRAP · คนคีย์อยู่ที่ created_by'
    AFTER issued_to_admin_id;
