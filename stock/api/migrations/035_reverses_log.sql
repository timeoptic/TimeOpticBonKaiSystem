-- ยกเลิกการเบิกของร้านเอง (TimeOptic) — แถวรับคืนชี้กลับไปที่แถวจ่ายออกที่มันยกเลิก
--
-- ร้านถามไว้ 12 ก.ย. 2026: "ถ้า TimeOptic เบิกผิดแก้อย่างไร ไม่มีที่แก้ให้เลย" · การเบิกของสาขา
-- ยกเลิกได้จากหน้าการเบิกจากสาขา (ผูกกันด้วย branch_issue_id) · การเบิกของร้านเองไม่มีแถวอื่น
-- ให้ผูก สมุดจึงบอกไม่ได้ว่าแถวจ่ายออกแถวไหนถูกคืนไปแล้ว และคนกดยกเลิกซ้ำจะคืนของสองรอบ
--
-- UNIQUE ไม่ใช่แค่ index — ฐานข้อมูลเองจะไม่ยอมให้มีแถวรับคืนสองแถวของแถวจ่ายออกเดียวกัน
-- ต่อให้สองคนกดพร้อมกัน · NULL ซ้ำกันได้ แถวอื่นทั้งหมดที่ไม่ได้ยกเลิกอะไรจึงไม่กระทบ
-- (ดู `Service\ShopIssue::cancel`)

ALTER TABLE inventory_logs
  ADD COLUMN reverses_log_id INT UNSIGNED NULL DEFAULT NULL
    COMMENT 'แถวรับคืนนี้ยกเลิกแถวจ่ายออกแถวไหน · เฉพาะการยกเลิกการเบิกของร้านเอง'
    AFTER branch_issue_id,
  ADD UNIQUE KEY uq_log_reverses (reverses_log_id);
