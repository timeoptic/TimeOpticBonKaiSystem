-- ใบสั่งตัดที่เปิดผิด ต้องปิดได้โดยไม่ต้องลบประวัติ
--
-- ใบสั่งตัด RX เปิดง่ายและเปิดผิดง่ายพอกัน — คนละคนไข้ ค่าสายตาสลับข้าง เลนส์
-- คนละรุ่น · จนถึงตอนนี้ใบที่เปิดผิดไม่มีทางออก มันค้างอยู่ในสมุดตลอดไป และ
-- ฝ่ายบัญชีก็ต้องคอยจำเองว่าใบไหนไม่นับ
--
-- ทางออกแยกเป็นสองแบบตามว่ามีเงินผูกอยู่หรือยัง:
--
--   ยังไม่ลงต้นทุน และยังไม่ตั้งราคาขาย
--     ไม่มีตัวเลขเงินที่ใครอ้างอิงไปแล้ว ลบทิ้งได้จริง (ลบ `rx_orders` ก่อน แล้ว
--     ค่อยลบแถวในสมุด — foreign key เป็น RESTRICT ตามกฎของ 012 ซึ่งห้ามการลบ
--     แบบลูกหายตามพ่อไปเงียบ ๆ ไม่ได้ห้ามการลบที่เก็บกวาดลูกเองก่อน)
--     RX_ORDER ไม่เคยผูกกับล็อต (`lot_id` NULL) ยอดคงเหลือของล็อตไหนจึงไม่ขยับ
--
--   ลงต้นทุนหรือตั้งราคาไปแล้ว
--     ตัวเลขนั้นเคยถูกอ่าน เคยถูกรวมในรายงาน ลบทิ้งคือแก้ประวัติ · ใบจึงถูก
--     "ยกเลิก" แทน: แถวเดิมอยู่ที่เดิม มีแถว RETURN คู่กันในสมุดบอกว่าใบนี้
--     ถูกยกเลิกวันไหน โดยใคร และคอลัมน์ข้างล่างนี้เป็นที่ให้สมุดใบสั่งกรองออก
--     จากรายการที่ยังเดินอยู่
--
-- คอลัมน์อยู่บน `rx_orders` ไม่ใช่บน `inventory_logs` เพราะสมุดคลังเป็นของกลาง
-- ที่ทุกชนิดรายการใช้ร่วมกัน ส่วน "ยกเลิก" เป็นเรื่องของใบสั่งตัดชนิดเดียว
-- ตารางนี้มีไว้เก็บสิ่งที่มีแต่ใบสั่งตัดเท่านั้นที่มีอยู่แล้ว (ดู 011)

ALTER TABLE rx_orders
  ADD COLUMN cancelled_at   DATETIME NULL DEFAULT NULL
    COMMENT 'วันที่ยกเลิกใบสั่ง — NULL = ใบนี้ยังเดินอยู่',
  ADD COLUMN cancelled_by   INT UNSIGNED NULL DEFAULT NULL
    COMMENT 'ใครยกเลิก',
  ADD COLUMN cancelled_note VARCHAR(500) NULL DEFAULT NULL
    COMMENT 'เหตุผลที่ยกเลิก — บังคับกรอก ใบที่ยกเลิกโดยไม่บอกเหตุผลคือใบที่อธิบายไม่ได้ทีหลัง';

-- RESTRICT เหมือน foreign key อื่นทุกเส้นที่ชี้ไป `admins` — ปิดบัญชีคนแล้ว
-- ประวัติว่าใครยกเลิกใบไหนต้องยังอ่านออก
ALTER TABLE rx_orders
  ADD CONSTRAINT fk_rx_cancelled_by FOREIGN KEY (cancelled_by) REFERENCES admins (id);

-- สมุดใบสั่งกรอง "ใบที่ยังเดินอยู่" ทุกครั้งที่เปิดหน้า
CREATE INDEX idx_rx_cancelled ON rx_orders (cancelled_at);
