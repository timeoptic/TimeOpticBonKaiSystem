-- บทบาทใหม่ หลังรวมสองระบบเข้าเป็นเว็บเดียว
--
-- ตอนที่ระบบคลังยังอยู่คนเดียว สามบทบาทก็พอ: เจ้าของร้าน ฝ่ายบัญชี พนักงาน
-- พอหน้าร้านกับคลังมาอยู่เว็บเดียวกัน คำว่า "พนักงาน" ตอบไม่ได้อีกต่อไปว่า
-- คนนี้เปิดระบบมาเพื่อขายของหรือมาจัดของ ซึ่งเป็นคำถามที่ต้องตอบให้ได้ตั้งแต่
-- วินาทีที่ล็อกอินเสร็จ เพราะเป็นตัวตัดสินว่าจะพาไปหน้าไหน
--
--   accountant -> admin   ชื่อเดิมบอกว่าทำบัญชี แต่สิทธิ์จริงคือดูแลระบบให้ทั้ง
--                         สองฝั่ง (จัดการผู้ใช้ ต้นทุน แดชบอร์ด) จึงเรียกตามสิ่ง
--                         ที่ทำ ไม่ใช่ตามแผนก
--   staff      -> sales    ห้าคนที่มีอยู่ล้วนเป็นคนหน้าร้าน (reception, sales,
--                         technician) ไม่มีใครทำงานคลังเป็นหลัก
--   + stock                พนักงานคลัง — บทบาทที่เมื่อก่อนไม่มีที่ให้เก็บ
--   + superuser            ผู้ดูแลระบบ อยู่เหนือเจ้าของร้าน สำหรับงานระบบ
--
-- ทำสามจังหวะเพราะ MySQL enum เก็บค่าเป็นเลขลำดับ ไม่ใช่ข้อความ: ต้องมีค่าใหม่
-- อยู่ในชนิดก่อนจึงจะเขียนค่าใหม่ลงแถวได้ และต้องเขียนแถวให้ครบก่อนจึงจะตัดค่า
-- เก่าทิ้งได้ ตัดก่อนแถวจะกลายเป็นค่าว่าง
--
-- ไม่มีการสร้างบัญชี superuser ที่นี่ — บัญชีต้องมีรหัสผ่าน และรหัสผ่านไม่ควร
-- อยู่ในไฟล์ที่ commit ลง git · สร้างด้วย `php api/bin/make-superuser.php`

-- 1. เปิดรับทั้งค่าเก่าและค่าใหม่พร้อมกัน
ALTER TABLE admins
  MODIFY COLUMN role
    ENUM('owner','accountant','staff','superuser','admin','sales','stock')
    NOT NULL DEFAULT 'staff';

-- 2. ย้ายแถวเดิมมาใช้ชื่อใหม่
UPDATE admins SET role = 'admin' WHERE role = 'accountant';
UPDATE admins SET role = 'sales' WHERE role = 'staff';

-- 3. ตัดค่าเก่าออก แล้วตั้งค่าปริยายเป็นบทบาทที่ให้สิทธิ์น้อยที่สุด
ALTER TABLE admins
  MODIFY COLUMN role
    ENUM('superuser','owner','admin','sales','stock')
    NOT NULL DEFAULT 'sales'
    COMMENT 'superuser = งานระบบ, owner = เจ้าของร้าน, admin = จัดการผู้ใช้และต้นทุน, sales = หน้าร้าน, stock = คลัง';
