-- จุดสั่งซื้อ: จำนวนต่ำสุดที่ควรมีติดคลังไว้เสมอ
--
-- ก่อนหน้านี้ระบบตอบได้แค่ "หมดแล้ว" ซึ่งสายเกินไป — เลนส์ที่หมดวันนี้คือลูกค้าที่
-- รอสองอาทิตย์ เจ้าของร้านรู้อยู่แล้วว่าตัวไหนควรมีติดไว้กี่ชิ้น แต่ความรู้นั้นอยู่ในหัว
-- คนเดียวและไม่มีที่ให้เก็บ คอลัมน์นี้คือที่เก็บนั้น
--
-- ตั้งบนสินค้า ไม่ใช่บนล็อต เพราะ "ควรมีเลนส์ตัวนี้กี่ชิ้น" เป็นคำถามเกี่ยวกับสินค้า
-- ล็อตเป็นแค่ครั้งที่รับเข้ามา และของชิ้นเดียวกันจากคนละล็อตก็นับรวมกันได้อยู่แล้ว
--
-- 0 = ไม่เตือน ไม่ใช่ "ขั้นต่ำเป็นศูนย์" — สินค้าส่วนใหญ่ในร้านไม่มีใครอยากถูกเตือน
-- ถึงมัน ค่าเริ่มต้นจึงต้องเป็นความเงียบ ไม่ใช่การเตือนทุกแถวตั้งแต่วันที่รัน migration นี้
--
-- INT ธรรมดา ไม่ใช่ UNSIGNED: ที่นี่ค่าติดลบไม่มีความหมาย แต่คอลัมน์จำนวนอื่นในตาราง
-- ฝั่งนี้เป็น INT กันหมด และการมีชนิดต่างออกไปหนึ่งคอลัมน์แลกมาแค่ความไม่สม่ำเสมอ
-- ค่าติดลบถูกกันที่ Catalog::minStock ก่อนถึงฐานข้อมูลอยู่แล้ว

ALTER TABLE products
  ADD COLUMN IF NOT EXISTS min_stock INT NOT NULL DEFAULT 0 AFTER base_selling_price;
