-- ขายของที่ยังไม่มีในคลังได้ แล้วรับเข้าทีหลังมาหักกลบ
--
-- ร้านขายกรอบที่ยังไม่ได้เข้าอยู่แล้ว — ลูกค้าสั่ง จ่ายเงิน ของมาถึงสัปดาห์หน้า
-- ระบบเดิมปฏิเสธการตัด (`insufficient`) ทำให้พนักงานต้องเลือกระหว่างไม่บันทึกการ
-- ขาย กับรับของเข้าลอย ๆ ก่อนเพื่อให้ตัดได้ · ทั้งสองทางทำให้ตัวเลขในระบบไม่ตรง
-- กับความจริง ซึ่งแย่กว่ายอดติดลบที่บอกตรง ๆ ว่าติดค้างอยู่เท่าไร
--
-- ยอดติดลบไม่ได้อยู่บนล็อตจริง — ล็อตคือของที่มาถึงจริงเป็นกล่อง ๆ ติดลบไม่ได้
-- ตามนิยาม · ส่วนที่ขายเกินไปอยู่บน "ล็อตค้างส่ง" ของสินค้านั้น ล็อตเดียวต่อ
-- สินค้าหนึ่งตัว (`lot_number` = `SHORT-<sku>`) ซึ่ง `Stock` สร้างให้เองเมื่อ
-- จำเป็น · ล็อตนี้ไม่มีต้นทุนเพราะยังไม่รู้ว่าจะซื้อมาเท่าไร และไม่ถูกหยิบไปตัด
-- ครั้งต่อไป เพราะการตัดเลือกเฉพาะล็อตที่ยอดเป็นบวก
--
-- ยอดคงเหลือของสินค้าคือผลรวมของทุกล็อตรวมล็อตค้างส่ง จึงติดลบได้ตามนโยบาย
-- และกลับเป็นบวกเองเมื่อของมาถึง — `Receiving` หักกลบให้ตอนรับเข้า
--
-- `initial_qty` ยังเป็น UNSIGNED เหมือนเดิม: จำนวนที่ "รับเข้ามา" ติดลบไม่ได้
-- แม้แต่กับล็อตค้างส่ง ซึ่งเกิดมาด้วยยอดรับเข้า 0

ALTER TABLE stock_lots
  MODIFY COLUMN remaining_qty INT NOT NULL DEFAULT 1
    COMMENT 'ติดลบได้เฉพาะล็อตค้างส่ง SHORT-<sku> — ของที่ขายไปก่อนจะรับเข้า';
