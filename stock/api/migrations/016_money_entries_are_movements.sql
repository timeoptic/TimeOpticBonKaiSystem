--
-- สองอย่างในระบบนี้ถูกบันทึกไว้ก่อนโดยไม่มีตัวเลขเงิน แล้วมีคนมากรอกทีหลัง:
--   · ต้นทุนของใบสั่งตัด RX — เปิดใบตอนสั่ง ราคาจากผู้ขายมาทีหลังพร้อมใบกำกับ
--   · ค่าของที่สาขาเบิกไป — ของออกไปก่อน เงินตามมาทีหลัง
--
-- เดิมทั้งสองอย่างเขียนทับของเก่า: ต้นทุน RX ไปเติมลงในแถว `RX_ORDER` ของวันที่
-- สั่ง และเงินจากสาขาไปอยู่ใน `branch_issues.settled_amount` ใบเดิม · ผลคือเงิน
-- ที่เพิ่งรับวันนี้ไปโผล่เป็นรายการของเดือนที่แล้ว รายงานของเดือนที่ปิดไปแล้ว
-- เปลี่ยนตัวเลขย้อนหลังได้เงียบ ๆ และหน้าความเคลื่อนไหวไม่มีบรรทัดไหนบอกเลยว่า
-- วันนี้มีใครกรอกอะไรเข้ามา
--
-- สองชนิดใหม่นี้คือ "เหตุการณ์เรื่องเงิน" ไม่ใช่การเคลื่อนของ จึงมี `quantity`
-- เป็นศูนย์เสมอ — กฎที่ว่ายอดคงเหลือของล็อตต้องเท่ากับผลรวมในสมุดจึงไม่กระทบ
-- และทุกที่ที่คิดมูลค่าเป็น `quantity * unit_cost` ก็ยังได้ศูนย์ ไม่นับซ้ำกับ
-- แถวของจริงที่มันอ้างถึง
--
--   COST   ลงต้นทุนใบสั่ง RX      `unit_cost` = ต้นทุนต่อชิ้นที่กรอก
--   SETTLE รับเงินค่าของจากสาขา   `unit_cost` = จำนวนเงินที่รับมาทั้งใบ

ALTER TABLE inventory_logs
  MODIFY COLUMN action_type
    ENUM('IN','OUT','ADJUST','RX_ORDER','RETURN','SCRAP','COST','SETTLE') NOT NULL;
