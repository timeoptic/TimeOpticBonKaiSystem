-- ราคาขายไม่เคยถูกบันทึกลงสมุด
--
-- `inventory_logs` เก็บ `unit_cost` มาตั้งแต่ต้น แต่ไม่เคยมีที่ให้ราคาขายเลย
-- ผลที่หน้าร้านเจอสองอย่าง:
--
--   1. เพิ่มเลนส์ใหม่จากหน้าขาย แล้วเปิดหน้า "ความเคลื่อนไหว" ดู — เห็นแต่ว่ามี
--      ของเข้ามา ไม่เห็นว่าตั้งขายเท่าไร ทั้งที่คนขายเพิ่งพิมพ์ตัวเลขนั้นไป
--   2. ราคาขายของงานสั่งตัดเปลี่ยนได้ตลอดตามที่ตกลงกับลูกค้าแต่ละบิล พอแก้แล้ว
--      ไม่มีบรรทัดไหนบอกว่าใครแก้เมื่อไร จากเท่าไรเป็นเท่าไร
--
-- ราคาขายบนแถวสมุดคือ "ราคา ณ ตอนนั้น" ไม่ใช่ราคาปัจจุบันของสินค้า — ซึ่งเป็น
-- สิ่งที่สมุดควรเก็บอยู่แล้ว ราคาปัจจุบันยังอยู่ที่ products.base_selling_price
-- เหมือนเดิม สองค่านี้ตั้งใจให้ต่างกันได้
--
-- PRICE เป็นชนิดรายการใหม่ ล้อกับ COST ที่มีอยู่แล้ว: quantity เป็นศูนย์เพราะ
-- ไม่มีของเคลื่อนที่ตอนแก้ราคา กฎ "ยอดคงเหลือของล็อต = ผลรวมในสมุด" จึงไม่กระทบ
-- และทุกที่ที่คิดมูลค่าเป็น quantity * unit_cost ก็ยังได้ศูนย์ ไม่นับซ้ำ

ALTER TABLE inventory_logs
  ADD COLUMN sale_price DECIMAL(12,2) NULL DEFAULT NULL
    COMMENT 'ราคาขาย ณ ตอนที่เกิดรายการนี้ — NULL = รายการนี้ไม่เกี่ยวกับราคาขาย'
    AFTER unit_cost;

ALTER TABLE inventory_logs
  MODIFY COLUMN action_type
    ENUM('IN','OUT','ADJUST','RX_ORDER','RETURN','SCRAP','COST','SETTLE','PRICE')
    NOT NULL;
