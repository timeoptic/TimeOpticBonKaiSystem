--
-- หน้าเว็บปิดปุ่มทันทีที่กดอยู่แล้ว แต่นั่นกันได้แค่การกดซ้ำที่เกิดในหน้าเดียวกัน
-- ไม่ได้กันเน็ตหลุดตอนกำลังส่ง แล้วพนักงานกดใหม่ ซึ่งเป็นเคสที่เกิดจริงหน้าร้าน
-- และจบด้วยใบขายสองใบที่เหมือนกันทุกอย่าง — ตอนปิดยอดสิ้นวันจะแยกไม่ออกว่า
-- ลูกค้าซื้อสองรอบจริง หรือระบบบันทึกซ้ำ
--
-- หน้าเว็บสร้างคีย์นี้หนึ่งค่าต่อหนึ่งตะกร้า (ตั้งแต่ตอนเปิดหน้า ไม่ใช่ตอนกดปุ่ม)
-- ส่งมากับคำขอ ถ้าคีย์ซ้ำ API คืนใบเดิมกลับไปแทนที่จะสร้างใหม่
--
-- UNIQUE บนคอลัมน์ที่ NULL ได้ — MariaDB ยอมให้มี NULL ซ้ำกันได้หลายแถว จึงยัง
-- บันทึกใบที่ไม่ส่งคีย์มาได้ (เช่นยิงจาก curl ตอนทดสอบ) โดยไม่ชนกันเอง

ALTER TABLE pos_sales
