-- เตือนของใกล้หมด "ตอนข้ามเส้น" ไม่ใช่ "ตอนอยู่ต่ำกว่าเส้น"
--
-- สคริปต์รายวันตอบคำถาม "ตอนนี้มีอะไรต่ำกว่าขั้นต่ำบ้าง" ได้ดีเพราะมันถามวันละครั้ง ·
-- พอย้ายมาเตือนทันทีที่ตัดสต็อก คำถามเดิมกลายเป็นคำถามที่ผิด: ของชิ้นที่ต่ำกว่า
-- ขั้นต่ำอยู่แล้วและถูกตัดอีกสิบรอบในเช้าวันเดียว จะได้สิบข้อความที่บอกเรื่องเดิม
-- แล้วกลุ่มจะกลายเป็นที่ที่ไม่มีใครอ่าน — ซึ่งเป็นสิ่งที่คอมเมนต์ในสคริปต์รายวัน
-- เขียนเตือนไว้ตั้งแต่แรก
--
-- คำถามที่ถูกคือ "เพิ่งข้ามเส้นลงมาหรือเปล่า" ซึ่งตอบไม่ได้จากยอดคงเหลืออย่างเดียว
-- ต้องรู้ด้วยว่าเคยบอกไปแล้วหรือยัง · ช่องนี้คือความจำนั้น:
--
--   NULL      = ตอนนี้ไม่ได้อยู่ในสถานะ "เตือนไปแล้ว" (ของยังพอ หรือเพิ่งได้ของเข้า)
--   มีค่า     = เตือนไปแล้วตั้งแต่เมื่อไร และจะไม่เตือนซ้ำจนกว่าของจะกลับขึ้นถึงขั้นต่ำ
--
-- เก็บเป็นเวลา ไม่ใช่ TINYINT — วันที่มีคนถามว่า "ทำไมไม่เตือน" คำตอบที่ใช้ได้คือ
-- "เตือนไปแล้วเมื่อวันที่เท่านี้" ไม่ใช่ "ธงเป็น 1"
--
-- ไม่ต้องเติมค่าเริ่มต้นย้อนหลัง: ของที่ต่ำกว่าขั้นต่ำอยู่ตอนนี้จะได้ข้อความหนึ่งใบ
-- ตอนถูกแตะครั้งถัดไป ซึ่งเป็นข้อความที่ถูกต้อง ไม่ใช่ข้อความซ้ำ

