-- ใบสั่งตัด RX สั่งโดยสาขาไหน
--
-- เดิมใบสั่งตัดไม่มีสาขา เพราะตอนออกแบบมันคืองานของร้านนี้ร้านเดียว · พอสาขา
-- อื่นเริ่มสั่งเลนส์ผ่านที่นี่ คำถามว่า "เดือนนี้สาขาไหนสั่งตัดไปกี่ใบ" ตอบไม่ได้
-- เลย ทั้งที่เป็นคำถามเดียวกับที่ `branch_issues` ตอบให้ฝั่งเบิกของอยู่แล้ว
--
-- NULL = ร้านนี้สั่งเอง ซึ่งเป็นกรณีส่วนใหญ่และเป็นค่าของใบเก่าทั้งหมด — ไม่ใช่
-- "ยังไม่ได้กรอก" · แยกสองอย่างนี้ไม่ได้ด้วยคอลัมน์เดียว และการบังคับให้เลือก
-- สาขาทุกใบเพื่อให้แยกออก แปลว่าคนหน้าร้านต้องเลือก "ร้านตัวเอง" วันละสิบครั้ง
--
-- RESTRICT เหมือน `branch_issues` — สาขาที่เคยสั่งของลบทิ้งไม่ได้ ไม่งั้นใบสั่ง
-- เก่าจะชี้ไปที่ว่างเปล่า

ALTER TABLE rx_orders
  ADD COLUMN branch_id INT UNSIGNED NULL DEFAULT NULL
    COMMENT 'สาขาที่สั่งใบนี้ — NULL คือร้านนี้สั่งเอง'
    AFTER log_id,
  ADD KEY idx_rx_branch (branch_id),
  ADD CONSTRAINT fk_rx_branch FOREIGN KEY (branch_id)
    REFERENCES branches (id) ON DELETE RESTRICT ON UPDATE CASCADE;
