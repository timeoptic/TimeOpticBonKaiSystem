-- หนึ่งคนถือได้หลายบทบาท · สิทธิ์คือยูเนียนของทุกบทบาทที่ถือ
--
-- `admins.role` เป็นคอลัมน์เดียวมาตลอด หนึ่งคนหนึ่งบทบาท ซึ่งตอบไม่ได้ว่าผู้จัดการ
-- ที่ขายหน้าร้านด้วยดูแลระบบด้วยควรเป็นอะไร — วันนี้ต้องเลือกอย่างเดียว แล้วอีกอย่าง
-- ถูกทำผ่านบัญชีที่สอง หรือไม่ก็ยกสิทธิ์ให้เกินที่ควร
--
-- ไฟล์นี้ทำฝั่งเพิ่มอย่างเดียว: สร้างตารางเชื่อม ยกของเดิมขึ้นไป และเปิดคอลัมน์
-- บังคับเปลี่ยนรหัส · `admins.role` ยังอยู่จนกว่าโค้ดจะเลิกอ่าน แล้วค่อยตัดใน 029
-- แยกสองไฟล์เพราะระหว่างนี้ทั้งสองรูปแบบต้องอ่านได้พร้อมกัน ไม่งั้นต้องหยุดร้าน

-- ── บทบาทเป็น ENUM ในตารางเชื่อม ไม่ใช่ตาราง `roles` แยกต่างหาก ────────────────
-- บทบาทเป็นค่าคงที่ในโค้ด (`Optic\Roles::ALL`) ไม่ใช่ของที่ร้านเพิ่มเองได้ · ตาราง
-- ชื่อบทบาทแยกจะเปิดช่องให้มีบทบาทในฐานที่โค้ดไม่รู้จัก แล้วสิทธิ์ของมันคือ
-- "ไม่มีอะไรเลย" โดยไม่มีอะไรเตือน — คนที่ถือมันจะกดอะไรก็ไม่ได้และไม่มีใครรู้ว่าทำไม
--
-- 'trainee' เป็นบทบาทใหม่ ถือชุดสิทธิ์เดียวกับ 'sales' ทุกช่อง ต่างกันแค่ป้าย
CREATE TABLE admin_roles (
  admin_id   INT UNSIGNED NOT NULL,
  role       ENUM('superuser','owner','admin','sales','trainee','stock') NOT NULL,
  granted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  granted_by INT UNSIGNED NULL COMMENT 'admins.id ของคนที่ให้สิทธิ์ · NULL = มาจาก migration',
  PRIMARY KEY (admin_id, role),
  CONSTRAINT fk_admin_roles_admin FOREIGN KEY (admin_id)   REFERENCES admins (id),
  CONSTRAINT fk_admin_roles_by    FOREIGN KEY (granted_by) REFERENCES admins (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='บทบาทของแต่ละบัญชี · หนึ่งแถวหนึ่งบทบาท สิทธิ์จริงคือยูเนียน';

-- ── ยกของเดิมขึ้นไป ─────────────────────────────────────────────────────────
-- ไม่ยกทั้งตาราง: 18 แถวใน `admins` เป็นแถวเงาที่ 027 สร้างให้พนักงานที่ไม่เคย
-- ล็อกอิน และได้ role 'sales' ติดมาเป็นค่าปริยายที่ไม่มีความหมาย (แถวไม่มีรหัสผ่าน
-- เข้าระบบไม่ได้อยู่แล้วไม่ว่าถืออะไร) · ยกขึ้นมาด้วยแปลว่าวันที่มีคนเปิดบัญชีให้เขา
-- สิทธิ์หน้าร้านจะติดมาเองโดยไม่มีใครกด ซึ่งกลับหัวกฎที่ 00fe623 เพิ่งวางไว้ว่า
-- "รับคนเข้าทำงาน" กับ "ให้คนนั้นเข้าระบบได้" เป็นคนละการตัดสินใจ
--
-- แต่ก็ไม่ตัดที่ "ล็อกอินได้" อย่างเดียว — id 2157 เป็น owner ที่ไม่มี username
-- มาตั้งแต่ก่อน 027 ซึ่งเป็นบทบาทที่มีคนตั้งไว้จริง ไม่ใช่ค่าปริยาย · เงื่อนไข
-- จึงเป็น "ล็อกอินได้ หรือ ถือบทบาทที่ไม่ใช่ค่าปริยาย"
INSERT INTO admin_roles (admin_id, role)
SELECT id, role FROM admins
 WHERE username IS NOT NULL OR role <> 'sales';

-- ── บังคับเปลี่ยนรหัสหลังถูกรีเซ็ต ──────────────────────────────────────────
-- ตั้งขึ้นตอนที่ *คนอื่น* ตั้งรหัสให้ (ปุ่มรีเซ็ต และช่องตั้งรหัสในหน้าแก้ไข)
-- ลงตอนที่เจ้าตัวเปลี่ยนเอง · รหัสที่แอดมินรู้จะได้ไม่ค้างอยู่เป็นรหัสจริง
ALTER TABLE admins
  ADD COLUMN must_change_password TINYINT(1) NOT NULL DEFAULT 0
    COMMENT 'รหัสถูกตั้งโดยคนอื่น — ต้องตั้งใหม่ก่อนใช้งานต่อ';

